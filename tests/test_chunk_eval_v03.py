"""Independent PR-033 evaluator with synthetic annotated IR only."""
import hashlib
import json

import pytest

from evals.benchmarks.chunker_groundtruth_v033 import (
    _read_cases, evaluate_corpus,
)
from paper2xmind.domain import canonical_serialize
from paper2xmind.chunking import (
    ChunkerConfig, StructureAwareChunker, GoldSpan,
    evaluate_gold_spans, validate_chunk_manifest,
)
from test_chunking_v03 import make_document, chunk


def make_gold(tmp_path):
    doc = make_document([(
        "ABC DEF GHI JKL MNO PQR STU VWX YZA " * 13,
        "paragraph", "methods", 0,
    )])
    source = tmp_path / "paper-ir.json"
    source.write_bytes(canonical_serialize(doc))
    payload = {
        "schema_version": "p2x_chunk_gold_v1",
        "corpus_name": "synthetic-authored-fixture",
        "cases": [{
            "id": "case1", "ir_path": source.name,
            "ir_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "license_note": "Synthetic text generated by test author",
            "gold_spans": [{
                "block_id": "b0000", "start_cp": 2, "end_cp": 12,
                "quote": doc.blocks[0].normalized_text[2:12],
            }],
        }],
    }
    manifest = tmp_path / "gold.json"
    manifest.write_text(json.dumps(payload), encoding="utf-8")
    return doc, manifest, payload


def test_independent_eval_complete_coverage_and_redundancy(tmp_path):
    doc, manifest, _ = make_gold(tmp_path)
    output = evaluate_corpus(manifest, budget=72, overlap=16)
    assert output["corpus_name"] == "synthetic-authored-fixture"
    assert output["unit"] == "utf8_bytes"
    case = output["results"][0]
    assert case["status"] == "evaluated"
    assert case["primary_coverage"] == 1.0
    assert case["context_redundancy_ratio"] > 0
    assert case["primary_fragment_recall"] is not None


def test_eval_with_no_overlap_reports_zero_duplication(tmp_path):
    doc, manifest, _ = make_gold(tmp_path)
    result = evaluate_corpus(manifest, budget=72, overlap=0)
    case = result["results"][0]
    assert case["status"] == "evaluated"
    assert case["context_redundancy_ratio"] == 0


def test_eval_detects_tampered_ir_and_missing_rights_note(tmp_path):
    _, manifest, data = make_gold(tmp_path)
    data["cases"][0]["ir_sha256"] = "0" * 64
    with pytest.raises(ValueError, match="GOLD_SOURCE_HASH_MISMATCH"):
        _read_cases(manifest.parent / "gold.json" if False else _new_manifest(tmp_path, data))
    data["cases"][0]["ir_sha256"] = hashlib.sha256(
        (tmp_path / "paper-ir.json").read_bytes()
    ).hexdigest()
    data["cases"][0]["license_note"] = ""
    with pytest.raises(ValueError, match="GOLD_CASE_METADATA_INVALID"):
        _read_cases(_new_manifest(tmp_path, data))


def _new_manifest(tmp_path, obj):
    path = tmp_path / "changed.json"
    path.write_text(json.dumps(obj), encoding="utf-8")
    return path


def test_eval_rejects_parent_path_traversal(tmp_path):
    _, _, data = make_gold(tmp_path)
    data["cases"][0]["ir_path"] = "../escape.json"
    with pytest.raises(ValueError, match="GOLD_SOURCE_PATH_TRAVERSAL"):
        _read_cases(_new_manifest(tmp_path, data))


def test_cross_boundary_evidence_quote_is_preserved_in_model_text():
    raw = "ABCDEF GHIJKLMN OPQRSTUV WXYZ " * 40
    doc = make_document([(raw, "paragraph", None, 0)])
    manifest = chunk(doc, budget=64, overlap=12)
    primary = [f for c in manifest.chunks for f in c.fragments
               if f.role == "primary"]
    boundary = primary[0].end_cp
    quote = raw[boundary - 5:boundary + 5]
    assert len(manifest.chunks) > 1
    assert quote not in manifest.chunks[0].content
    # The next chunk has a context suffix + primary following text. Since both
    # fragments belong to the same block, render_fragments joins them with no
    # fabricated newline and preserves exact source quote contiguously.
    assert quote in manifest.chunks[1].content
    gold = GoldSpan(block_id="b0000", start_cp=boundary - 5,
                    end_cp=boundary + 5, quote=quote)
    recall = evaluate_gold_spans(doc, manifest, [gold])
    assert recall.in_any_chunk == 1
    assert recall.in_primary_chunk == 0
    audit = validate_chunk_manifest(doc, manifest)
    assert audit.context_codepoints > 0
